package com.shatteredpixel.shatteredpixeldungeon.actors.hero.abilities.gnoll;

import com.shatteredpixel.shatteredpixeldungeon.actors.buffs.Buff;
import com.shatteredpixel.shatteredpixeldungeon.actors.buffs.FlavourBuff;
import com.shatteredpixel.shatteredpixeldungeon.actors.buffs.Invisibility;
import com.shatteredpixel.shatteredpixeldungeon.actors.hero.Hero;
import com.shatteredpixel.shatteredpixeldungeon.actors.hero.Talent;
import com.shatteredpixel.shatteredpixeldungeon.actors.hero.abilities.ArmorAbility;
import com.shatteredpixel.shatteredpixeldungeon.items.armor.ClassArmor;
import com.shatteredpixel.shatteredpixeldungeon.ui.HeroIcon;

public class Ambush extends ArmorAbility {

	{
		baseChargeUse = 35f;
	}

	@Override
	protected void activate(ClassArmor armor, Hero hero, Integer target) {
		Ready ready = Buff.prolong(hero, Ready.class, 8f + 3f * hero.pointsInTalent(Talent.AMBUSH_EDGE));
		ready.bonus = 4 + 3 * hero.pointsInTalent(Talent.AMBUSH_OPENING);
		ready.halfOnSeen = hero.pointsInTalent(Talent.AMBUSH_FADE) > 0;
		hero.sprite.operate(hero.pos);
		armor.charge -= chargeUse(hero);
		armor.updateQuickslot();
		Invisibility.dispel();
		hero.spendAndNext(1f);
	}

	public static class Ready extends FlavourBuff {
		public int bonus = 4;
		public boolean halfOnSeen = false;
	}

	@Override
	public int icon() {
		return HeroIcon.SMOKE_BOMB;
	}

	@Override
	public Talent[] talents() {
		return new Talent[]{Talent.AMBUSH_OPENING, Talent.AMBUSH_EDGE, Talent.AMBUSH_FADE, Talent.HEROIC_ENERGY};
	}
}
